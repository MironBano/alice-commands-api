from models import ParsedCommand

NOW = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _cmd(
    category_id: str,
    title: str,
    phrases: list[str],
    effect: str,
    *,
    requires_alice: bool = True,
    requires_plus: bool = False,
    devices: list[str] | None = None,
    tags: list[str] | None = None,
    source_url: str | None = None,
) -> ParsedCommand:
    cat = CATEGORY_BY_ID[category_id]
    url = source_url or cat.source_url
    tag_list = list(tags or [category_id])
    return ParsedCommand(
        id=stable_command_id(category_id, phrases[0]),
        category_id=category_id,
        title_ru=title,
        phrases=phrases,
        effect_description_ru=effect,
        source_url=url,
        requires_alice_word=requires_alice,
        requires_plus=requires_plus,
        device_types=devices or cat.device_types or ["station", "phone"],
        tags=tag_list,
        source_priority="primary",
        updated_at=NOW,
    )


